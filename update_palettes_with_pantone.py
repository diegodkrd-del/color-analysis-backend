# Update pdf_generator.py file
pdf_path = r'C:\Users\dkven\color_analysis_backend\pdf_generator.py'
with open(pdf_path, 'r', encoding='utf-8') as f:
    content = f.read()

# Function to add pantone key to dictionaries in SUBSEASON_PALETTES
def add_pantone(match):
    name = match.group(1)
    hex_code = match.group(2)
    pantone = PANTONE_TCX_MAP.get(hex_code, '17-1563 TCX')
    return f"{{'name': '{name}', 'hex': '{hex_code}', 'pantone': '{pantone}'}}"

updated_content = re.sub(r"\{'name': '([^']+)', 'hex': '([^']+)'\}", add_pantone, content)

with open(pdf_path, 'w', encoding='utf-8') as f:
    f.write(updated_content)

